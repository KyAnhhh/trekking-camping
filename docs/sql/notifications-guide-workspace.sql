BEGIN;
INSERT INTO roles(name) VALUES ('ROLE_GUIDE') ON CONFLICT(name) DO NOTHING;
ALTER TABLE guides ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_guides_user ON guides(user_id);
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    event_key VARCHAR(200) NOT NULL,
    title VARCHAR(180) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    link VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,
    email_status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMP WITH TIME ZONE,
    UNIQUE(user_id,event_key)
);
CREATE INDEX IF NOT EXISTS idx_notifications_owner ON notifications(user_id,created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_mail ON notifications(email_status,next_attempt_at);
CREATE TABLE IF NOT EXISTS booking_attendance (
    booking_id BIGINT PRIMARY KEY REFERENCES bookings(id),
    present_count INTEGER NOT NULL CHECK(present_count>=0),
    revision BIGINT NOT NULL,
    marked_by_guide_id BIGINT NOT NULL REFERENCES guides(id),
    marked_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMIT;

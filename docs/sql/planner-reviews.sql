-- Review and apply manually on a backed-up database. Not executed by the application.
-- Existing users, bookings and tour_reviews tables must already exist.
BEGIN;
CREATE TABLE IF NOT EXISTS saved_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_saved_plans_owner_created ON saved_plans(user_id, created_at);
-- If legacy duplicate reviews exist, this fails and rolls back. Review duplicates; do not delete blindly.
CREATE UNIQUE INDEX IF NOT EXISTS uq_tour_reviews_booking ON tour_reviews(booking_id);
COMMIT;

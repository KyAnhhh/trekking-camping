-- Apply explicitly before enabling the booking change request UI. No existing rows changed.
BEGIN;
CREATE TABLE IF NOT EXISTS booking_change_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL REFERENCES bookings(id),
 original_schedule_id BIGINT NOT NULL REFERENCES tour_schedules(id),
 target_schedule_id BIGINT REFERENCES tour_schedules(id),
 type VARCHAR(20) NOT NULL CHECK(type IN ('CANCEL','RESCHEDULE')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 reason VARCHAR(1000) NOT NULL,
 admin_note VARCHAR(1000), reviewed_by VARCHAR(254),
 quoted_amount NUMERIC(19,2), target_snapshot TEXT,
 created_at TIMESTAMP NOT NULL, reviewed_at TIMESTAMP,
 CHECK ((type='CANCEL' AND target_schedule_id IS NULL) OR (type='RESCHEDULE' AND target_schedule_id IS NOT NULL AND quoted_amount IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_change_pending ON booking_change_requests(booking_id) WHERE status='PENDING';
CREATE INDEX IF NOT EXISTS idx_booking_change_queue ON booking_change_requests(status,id);
COMMIT;

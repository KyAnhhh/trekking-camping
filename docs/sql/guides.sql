BEGIN;
CREATE TABLE IF NOT EXISTS guides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    avatar_url VARCHAR(255),
    bio VARCHAR(4000),
    experience_since INTEGER,
    specialties VARCHAR(500),
    languages VARCHAR(200),
    phone VARCHAR(30),
    email VARCHAR(254),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS schedule_guides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES tour_schedules(id),
    guide_id BIGINT NOT NULL REFERENCES guides(id),
    role VARCHAR(20) NOT NULL CHECK (role IN ('LEAD', 'ASSISTANT')),
    UNIQUE (schedule_id, guide_id)
);
CREATE INDEX IF NOT EXISTS idx_schedule_guides_guide ON schedule_guides(guide_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_schedule_guides_lead ON schedule_guides(schedule_id) WHERE role = 'LEAD';
-- Preserve tour_schedules.guide_name / guide_phone until admins explicitly map each departure.
COMMIT;

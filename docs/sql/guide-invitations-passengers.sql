-- Review and apply to a backed-up test database first. Not run automatically.
-- Requires notifications-guide-workspace.sql and the existing bookings/users/guides schema.
BEGIN;
INSERT INTO roles(name) VALUES ('ROLE_GUIDE') ON CONFLICT(name) DO NOTHING;
CREATE TABLE IF NOT EXISTS guide_invitations (
    guide_id BIGINT PRIMARY KEY REFERENCES guides(id), email VARCHAR(254) NOT NULL,
    token_hash VARCHAR(64) UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','ACCEPTED','REVOKED')),
    sent_at TIMESTAMP WITH TIME ZONE, expires_at TIMESTAMP WITH TIME ZONE,
    accepted_at TIMESTAMP WITH TIME ZONE, window_start TIMESTAMP WITH TIME ZONE,
    sends_in_window INTEGER NOT NULL DEFAULT 0, invited_by BIGINT REFERENCES users(id)
);
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS passenger_revision BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS booking_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id), position INTEGER NOT NULL CHECK (position > 0),
    full_name VARCHAR(150) NOT NULL,
    attendance_status VARCHAR(20) NOT NULL DEFAULT 'NOT_CHECKED' CHECK (attendance_status IN ('NOT_CHECKED','PRESENT','ABSENT')),
    revision BIGINT NOT NULL DEFAULT 0, marked_at TIMESTAMP WITH TIME ZONE,
    UNIQUE(booking_id, position)
);
CREATE TABLE IF NOT EXISTS passenger_attendance_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id), passenger_id BIGINT NOT NULL REFERENCES booking_passengers(id),
    guide_id BIGINT NOT NULL REFERENCES guides(id), previous_status VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL, revision BIGINT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(passenger_id, revision)
);
CREATE INDEX IF NOT EXISTS idx_passenger_audit_booking ON passenger_attendance_audit(booking_id, id);
-- No health data is copied and no legacy aggregate attendance is assigned to named people.
COMMIT;

BEGIN;
SET LOCAL lock_timeout='5s';
ALTER TABLE schedule_guides ADD COLUMN IF NOT EXISTS response_status VARCHAR(20) NOT NULL DEFAULT 'LEGACY';
ALTER TABLE schedule_guides ADD COLUMN IF NOT EXISTS response_reason VARCHAR(1000);
ALTER TABLE schedule_guides ADD COLUMN IF NOT EXISTS responded_at TIMESTAMP WITH TIME ZONE;
CREATE TABLE IF NOT EXISTS guide_assignment_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id BIGINT NOT NULL,
 guide_id BIGINT NOT NULL,
 actor VARCHAR(254) NOT NULL,
 action VARCHAR(30) NOT NULL,
 reason VARCHAR(1000),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_guide_assignment_events_schedule ON guide_assignment_events(schedule_id,id);
COMMIT;

BEGIN;
CREATE TABLE IF NOT EXISTS booking_checklist (
 booking_id BIGINT NOT NULL REFERENCES bookings(id), item_key VARCHAR(80) NOT NULL,
 label VARCHAR(500), checked BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(booking_id,item_key)
);
CREATE TABLE IF NOT EXISTS notification_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id), email_enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS guide_trip_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id BIGINT NOT NULL REFERENCES tour_schedules(id), guide_id BIGINT NOT NULL REFERENCES guides(id),
 summary VARCHAR(4000) NOT NULL, incidents VARCHAR(4000) NOT NULL, suggestions VARCHAR(2000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED' CHECK(status IN ('SUBMITTED','REVIEWED')),
 admin_note VARCHAR(2000), reviewed_by VARCHAR(254), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMPTZ, UNIQUE(schedule_id,guide_id)
);
CREATE INDEX IF NOT EXISTS idx_guide_reports_queue ON guide_trip_reports(status,id);
CREATE TABLE IF NOT EXISTS review_photos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES tour_reviews(id), url VARCHAR(300) NOT NULL UNIQUE,
 approved BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_review_photos_review ON review_photos(review_id,id);
COMMIT;
